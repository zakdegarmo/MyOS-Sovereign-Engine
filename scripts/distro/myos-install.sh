#!/usr/bin/env bash
# ==============================================================================
# MyOS Sovereign Bare-Metal Installer
# Installs the Live MyOS Image directly to an internal drive's boot sector & EFI.
# ==============================================================================

set -euo pipefail

# Ensure running as root
if [ "$EUID" -ne 0 ]; then
    echo "[-] Error: Please run as root: sudo ./myos-install.sh"
    exit 1
fi

clear
cat << "EOF"
  __  __       ____   _____   ____                             _             
 |  \/  |     / __ \ / ____| |  _ \                           (_)            
 | \  / |_   | |  | | (___   | |_) | __ _ _ __ ___ ______ _ __ ___   ___  ___ 
 | |\/| | | | | |  | |\___ \  |  _ < / _` | '__/ _ \______| '_ ` _ \ / _ \/ __|
 | |  | | |_| | |__| |____) | | |_) | (_| | | |  __/      | | | | | | (_) \__ \
 |_|  |_|\__, |\____/|_____/  |____/ \__,_|_|  \___|      |_| |_| |_|\___/|___/
          __/ |                                                                
         |___/      S O V E R E I G N   B A R E - M E T A L   I N S T A L L E R 
EOF
echo ""
echo "=============================================================================="
echo " Welcome to the MyOS Sovereign Bare-Metal Installer."
echo " This wizard will format your target drive and install the full 3D OS."
echo "=============================================================================="
echo ""

# 1. Detect and List Drives
echo "[*] Available storage devices:"
echo "------------------------------------------------------------------"
lsblk -d -p -n -o NAME,SIZE,MODEL,TYPE | grep -E "disk"
echo "------------------------------------------------------------------"
echo ""

read -rp "Enter target drive path (e.g., /dev/nvme0n1 or /dev/sda): " TARGET_DRIVE

if [ ! -b "$TARGET_DRIVE" ]; then
    echo "[-] Invalid drive device: $TARGET_DRIVE"
    exit 1
fi

echo ""
echo "!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!"
echo " WARNING: ALL DATA ON $TARGET_DRIVE WILL BE PERMANENTLY ERASED!"
echo "!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!"
read -rp "Type 'SOVEREIGN' in capital letters to confirm and proceed: " CONFIRMATION

if [ "$CONFIRMATION" != "SOVEREIGN" ]; then
    echo "[-] Installation cancelled. No changes were made."
    exit 0
fi

echo ""
echo "[+] Step 1/6: Partitioning $TARGET_DRIVE (GPT / EFI / Ext4)..."
# Wipe signatures
wipefs -a "$TARGET_DRIVE"

# Create GPT: 512M EFI System Partition + remainder Ext4 Root
parted -s "$TARGET_DRIVE" \
    mklabel gpt \
    mkpart ESP fat32 1MiB 513MiB \
    set 1 esp on \
    mkpart MyOSRoot ext4 513MiB 100%

# Resolve partition naming (handle /dev/nvme0n1p1 vs /dev/sda1)
if [[ "$TARGET_DRIVE" =~ [0-9]$ ]]; then
    PART_EFI="${TARGET_DRIVE}p1"
    PART_ROOT="${TARGET_DRIVE}p2"
else
    PART_EFI="${TARGET_DRIVE}1"
    PART_ROOT="${TARGET_DRIVE}2"
fi

# Wait for kernel to register partition table
partprobe "$TARGET_DRIVE"
sleep 2

echo "[+] Step 2/6: Formatting filesystems..."
mkfs.vfat -F32 -n "MYOS_EFI" "$PART_EFI"
mkfs.ext4 -F -L "MYOS_ROOT" "$PART_ROOT"

echo "[+] Step 3/6: Mounting target filesystems..."
TARGET_MNT="/mnt/myos-target"
mkdir -p "$TARGET_MNT"
mount "$PART_ROOT" "$TARGET_MNT"
mkdir -p "$TARGET_MNT/boot/efi"
mount "$PART_EFI" "$TARGET_MNT/boot/efi"

echo "[+] Step 4/6: Syncing MyOS Sovereign System to disk (rsync)..."
rsync -aAXv --info=progress2 \
    --exclude={"/dev/*","/proc/*","/sys/*","/tmp/*","/run/*","/mnt/*","/media/*","/lost+found"} \
    / "$TARGET_MNT/"

# Ensure mountpoint directories exist
mkdir -p "$TARGET_MNT"/{dev,proc,sys,tmp,run,mnt,media}

echo "[+] Step 5/6: Configuring fstab & UUIDs..."
UUID_ROOT=$(blkid -s UUID -o value "$PART_ROOT")
UUID_EFI=$(blkid -s UUID -o value "$PART_EFI")

cat << EOF > "$TARGET_MNT/etc/fstab"
# /etc/fstab generated by MyOS Sovereign Installer
UUID=$UUID_ROOT  /          ext4  defaults,noatime,errors=remount-ro  0  1
UUID=$UUID_EFI   /boot/efi  vfat  umask=0077                          0  1
tmpfs            /tmp       tmpfs defaults,noatime,mode=1777          0  0
EOF

echo "[+] Step 6/6: Installing GRUB EFI Bootloader..."
# Bind mount virtual filesystems for chroot
for fs in dev proc sys; do
    mount --bind "/$fs" "$TARGET_MNT/$fs"
done

chroot "$TARGET_MNT" /bin/bash -c "
    grub-install --target=x86_64-efi --efi-directory=/boot/efi --bootloader-id=MyOS --recheck
    update-grub
    systemctl enable myos-kiosk.service
    systemctl enable myos-bridge.service
    systemctl enable ollama.service
"

# Clean unmount
echo "[*] Finalizing unmount..."
umount -R "$TARGET_MNT"

echo ""
echo "=============================================================================="
echo " [SUCCESS] MyOS Sovereign OS has been installed to $TARGET_DRIVE!"
echo " Remove your USB boot drive and reboot your machine."
echo " Welcome to your sovereign native 3D computing substrate."
echo "=============================================================================="
