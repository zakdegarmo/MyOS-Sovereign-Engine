/**
 * Generates the full 100-point relationship trait set for a subject.
 * Note: Actual answers to "Who, What, When, Where, Why, How" for each trait
 * are typically generated by an LLM (Mistral) using this matrix as a prompt structure.
 */
export function getRelationshipTemplate(subject: string) {
    const template: any = {
        subject,
        traits: {}
    };

    PILLARS.forEach(p1 => {
        const row: any = {};
        PILLARS.forEach(p2 => {
            const rel = RELATIONSHIP_MATRIX[p1][p2];
            row[p2] = rel;
        });
        template.traits[p1] = row;
    });

    return template;
}

/**
 * Generates the specific prompt query for the Relationship Matrix.
 * 10 Pillars x 10 Relationships = 100 deep data points.
 */
export function generateRelationshipMatrixQuery(subject: string): string {
    const template = getRelationshipTemplate(subject);
    const jsonTemplate = JSON.stringify(template.traits, null, 2);

    return `CURRENT_SUBJECT=${subject}
I need a deep ontological scan of the CURRENT_SUBJECT. 
Using the Relationship Matrix (10 Pillars with 10 Relationships each), provide a valid JSON object where each value is a concise, 1-3 word "Who/What/When/Where/Why/How" answer that describes the specific relationship.

IMPORTANT: The ontological truth for these relationships is stored in 'apps/web/public/library/[Pillar]/[Relationship].md'. Review the files in that directory to ensure the scan aligns with the established universe.

STRUCTURE:
${jsonTemplate}

Return ONLY the completed JSON object. No preamble.`;
}

